"""Export FastAPI OpenAPI and small schema-only TypeScript declarations.

Run from any directory after installing apps/api/requirements.txt.
--from-snapshot regenerates types without importing API dependencies.
The initial snapshot is marked bootstrap-unverified because this host cannot
install FastAPI. A normal export replaces it with the actual app OpenAPI.
"""

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OPENAPI_PATH = ROOT / "contracts" / "openapi.json"
TYPES_PATH = ROOT / "apps" / "web" / "src" / "lib" / "api" / "generated.d.ts"


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return f'components["schemas"][{json.dumps(name)}]'
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return " | ".join(ts_type(item) for item in schema[union])
    if "allOf" in schema:
        return " & ".join(ts_type(item) for item in schema["allOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"({ts_type(schema.get('items', {}))})[]"
    if kind == "object" or "properties" in schema:
        required = set(schema.get("required", []))
        properties = [
            f'{json.dumps(key)}{"" if key in required else "?"}: {ts_type(value)};'
            for key, value in sorted(schema.get("properties", {}).items())
        ]
        additional = schema.get("additionalProperties", False)
        if isinstance(additional, dict):
            properties.append(f"[key: string]: {ts_type(additional)};")
        elif additional:
            properties.append("[key: string]: unknown;")
        return "{ " + " ".join(properties) + " }"
    return {
        "string": "string", "number": "number", "integer": "number",
        "boolean": "boolean", "null": "null",
    }.get(kind, "unknown")


def render_types(document: dict) -> str:
    rows = [
        "// Generated by scripts/export-contracts.py. Do not edit manually.",
        "// Values still require server validation; TS cannot express numeric bounds.",
        "export interface components {",
        "  schemas: {",
    ]
    for name, schema in sorted(document["components"]["schemas"].items()):
        rows.append(f"    {json.dumps(name)}: {ts_type(schema)};")
    rows.extend(["  };", "}", ""])
    return "\n".join(rows)


def schema_signature(schema):
    """Keep validation semantics; omit generated documentation annotations."""
    if isinstance(schema, list):
        return [schema_signature(item) for item in schema]
    if not isinstance(schema, dict):
        return schema
    result = {}
    for key, value in schema.items():
        if key in {"title", "description", "example", "examples"}:
            continue
        if key in {"properties", "$defs"}:
            # A property named title/description is still a real contract field.
            result[key] = {name: schema_signature(child) for name, child in value.items()}
        elif key == "required":
            result[key] = sorted(value)
        else:
            result[key] = schema_signature(value)
    return result


def contract_signature(document: dict) -> dict:
    """Paths, request/response shape and schemas are shared API semantics."""
    paths = {}
    for path, methods in document["paths"].items():
        paths[path] = {}
        for method, operation in methods.items():
            if method not in {"get", "post", "put", "patch", "delete", "options", "head"}:
                continue
            response_shapes = {}
            for status, response in operation["responses"].items():
                response_shapes[status] = {
                    mime: schema_signature(media.get("schema", {}))
                    for mime, media in response.get("content", {}).items()
                }
            body = operation.get("requestBody", {})
            paths[path][method] = {
                "responses": response_shapes,
                "parameters": [
                    {"name": parameter["name"], "in": parameter["in"],
                     "required": parameter.get("required", False),
                     "schema": schema_signature(parameter.get("schema", {}))}
                    for parameter in operation.get("parameters", [])
                ],
                "body_required": body.get("required", False),
                "body": {mime: schema_signature(media.get("schema", {}))
                         for mime, media in body.get("content", {}).items()},
            }
    return {"schemas": {name: schema_signature(schema)
                        for name, schema in document["components"]["schemas"].items()},
            "paths": paths}


def first_difference(expected, actual, path="contract") -> str | None:
    if isinstance(expected, dict) and isinstance(actual, dict):
        if expected.keys() != actual.keys():
            return f"{path}: keys differ (snapshot={sorted(expected)}, runtime={sorted(actual)})"
        for key in sorted(expected):
            difference = first_difference(expected[key], actual[key], f"{path}.{key}")
            if difference:
                return difference
        return None
    if isinstance(expected, list) and isinstance(actual, list):
        if len(expected) != len(actual):
            return f"{path}: list lengths differ"
        for index, (left, right) in enumerate(zip(expected, actual)):
            difference = first_difference(left, right, f"{path}[{index}]")
            if difference:
                return difference
        return None
    return None if expected == actual else f"{path}: snapshot={expected!r}, runtime={actual!r}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--from-snapshot", action="store_true")
    parser.add_argument("--check", action="store_true", help="Check without writing")
    args = parser.parse_args()
    if args.from_snapshot:
        document = json.loads(OPENAPI_PATH.read_text(encoding="utf-8"))
    else:
        sys.path.insert(0, str(ROOT / "apps" / "api"))
        try:
            from app.main import app
        except ModuleNotFoundError as exc:
            print(
                f"API dependencies unavailable ({exc.name}). Install "
                "apps/api/requirements-dev.txt, or use --from-snapshot for types only.",
                file=sys.stderr,
            )
            return 2
        document = app.openapi()
    openapi_text = json.dumps(document, indent=2, sort_keys=True) + "\n"
    types_text = render_types(document)
    expected = [(TYPES_PATH, types_text)]
    if args.check:
        if not args.from_snapshot:
            snapshot = json.loads(OPENAPI_PATH.read_text(encoding="utf-8"))
            difference = first_difference(contract_signature(snapshot), contract_signature(document))
            if difference:
                print("OpenAPI semantic drift: " + difference)
                return 1
        stale = [str(path.relative_to(ROOT)) for path, content in expected
                 if not path.exists() or path.read_text(encoding="utf-8") != content]
        if stale:
            print("Contract artifacts need regeneration: " + ", ".join(stale))
            return 1
        print("Contract artifacts are current for the selected source.")
        return 0
    if not args.from_snapshot:
        expected.insert(0, (OPENAPI_PATH, openapi_text))
    for path, content in expected:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print(path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
